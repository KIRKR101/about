import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OPENING = `# kirkr.xyz — full site text

This file is generated by scripts/generate-llms-full.mjs and contains the complete
text of every essay and project page on kirkr.xyz. It is the long-form companion to
llms.txt: the index lives at https://kirkr.xyz/llms.txt.

## Contents

- [Writings](#writings)
- [Projects](#projects)

## Writings

`;

const stripFrontmatter = (md) => md.replace(/^---\s*\n[\s\S]*?\n---\s*\n/, '');
const frontmatter = (md) => md.match(/^---\s*\n([\s\S]*?)\n---\s*\n/)?.[1] ?? md;
const frontmatterField = (md, field) =>
	frontmatter(md).match(new RegExp(`^${field}:\\s*['"]?([^\\n'"]+)`, 'm'))?.[1];
const cleanBody = (md) =>
	md
		// Obsidian-style images: ![[file|alt]] -> alt text
		.replace(/!\[\[[^|\]]+(?:\|([^\]]+))?\]\]/g, (_m, alt) => alt ?? '')
		// Inline SVGs: ![alt](/writing/x.svg) -> alt text
		.replace(/!\[([^\]]*)\]\(\/?writing\/[^)]+\.svg\)/g, (_m, alt) => alt ?? '')
		// External images: keep only the caption if present
		.replace(/!\[[^\]]*\]\([^)]*\)/g, '')
		.replace(/\n{3,}/g, '\n\n')
		.trim();

const collect = (dir) =>
	readdirSync(join(ROOT, dir), { withFileTypes: true })
		.filter((e) => e.isDirectory())
		.map((e) => join(ROOT, dir, e.name, '+page.md'))
		.filter((p) => {
			try {
				readFileSync(p);
				return true;
			} catch {
				return false;
			}
		});

const render = (path, heading) => {
	const md = readFileSync(path, 'utf8');
	const title = frontmatterField(md, 'title');
	const date = frontmatterField(md, 'date');
	const body = cleanBody(stripFrontmatter(md));
	return `## ${heading}: ${title}${date ? ` (${date})` : ''}

${body}

`;
};

let out = OPENING;
const writings = collect('src/routes/writing').sort((a, b) => {
	const da = frontmatterField(readFileSync(a, 'utf8'), 'date');
	const db = frontmatterField(readFileSync(b, 'utf8'), 'date');
	return da && db ? (db < da ? -1 : 1) : 0;
});
const projects = collect('src/routes/project').sort();

for (const w of writings) out += render(w, 'Writing');
out += `\n## Projects\n\n`;
for (const p of projects) out += render(p, 'Project');

writeFileSync(join(ROOT, 'static', 'llms-full.txt'), out);
console.log(`Wrote static/llms-full.txt (${Buffer.byteLength(out, 'utf8').toLocaleString()} bytes, ${writings.length} writings, ${projects.length} projects)`);